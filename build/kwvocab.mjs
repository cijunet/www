// 事件打分：分数越高越值得上首页（有词句可配、年代久远、文化味浓）
const CULTURAL_RE = /诗人|作家|画家|音乐家|作曲家|小说|诗|词|诞生|出生|诞辰|逝世|忌辰|出版|发表|首演|戏曲|京剧|歌剧|童话|寓言|文学|诺贝尔|获奖|登顶|远航|名曲|名画/;
export function scoreEvent(ev, kwHits) {
  let s = kwHits.length * 3;
  if (ev.y <= 1949) s += 2;
  if (ev.y <= 1911) s += 1;
  if (CULTURAL_RE.test(ev.t)) s += 2;
  return s;
}

// 从一天的全部事件里选出最适合上首页的 N 条
export function pickEvents(events, vocab, n = 6) {
  const scored = events
    .map(ev => {
      const kw = vocab.filter(w => w && ev.t.indexOf(w) > -1);
      return { ev, kw, score: scoreEvent(ev, kw) };
    })
    .sort((a, b) => b.score - a.score || a.ev.y - b.ev.y);
  return scored.slice(0, n)
    .sort((a, b) => a.ev.y - b.ev.y) // 展示时仍按年代排
    .map(({ ev, kw }) => ({ y: ev.y, t: ev.t.length > 42 ? ev.t.slice(0, 42) + '…' : ev.t, kw }));
}
